export function generateInitialCollection(): CDItem[] {
  const collection: CDItem[] = [...PRIMARY_COLLECTION];
  let idCounter = 100;
  
  // Fill the remaining spots up to exactly 324 total CDs across exactly 87 Bands!
  // Already in PRIMARY_COLLECTION: Pearl Jam (8), Pink Floyd (4), Nirvana (3), Radiohead (4 + 1 loaned) = 20 CDs across 4 bands.
  
  for (const band of FAMOUS_BANDS) {
    for (const album of band.albums) {
      // Check if already in primary
      const exists = collection.some(
        (c) => c.artist.toLowerCase() === band.name.toLowerCase() && c.title.toLowerCase() === album.toLowerCase()
      );
      if (!exists && collection.length < 324) {
        idCounter++;
        const year = 1970 + Math.floor(Math.random() * 54);
        const conditions: Array<'Mint' | 'Very Good' | 'Good' | 'Fair' | 'Sealed'> = ['Mint', 'Very Good', 'Mint', 'Very Good', 'Sealed'];
        const cond = conditions[idCounter % conditions.length];
        const shelfLetter = String.fromCharCode(65 + (idCounter % 6)); // A-F
        const shelfNum = (idCounter % 5) + 1;
        
        collection.push({
          id: `col-gen-${idCounter}`,
          title: album,
          artist: band.name,
          year,
          mediaFormat: idCounter % 7 === 0 ? 'Vinyl' : 'CD',
          label: 'Original Pressing',
          trackCount: 10 + (idCounter % 6),
          status: 'collection',
          condition: cond,
          shelfLocation: `Prateleira ${shelfLetter}${shelfNum}`,
          rating: 4 + (idCounter % 2),
          actualPrice: `${10 + (idCounter % 15)} €`,
          addedAt: new Date(Date.now() - idCounter * 86400000 * 3).toISOString(),
          addedToCollectionDate: new Date(Date.now() - idCounter * 86400000 * 3).toISOString(),
        });
      }
    }
  }

  return collection;
}

